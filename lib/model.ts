// Token Radar model (radar-2): one sealed snapshot in, one ranked board out.
//
// The board ranks pre-token protocols by implied launch value. Implied value is
// derived only from the snapshot's own figures, never from a hand-written list
// of names, and the same function scores every row:
//
//   peer     = median market-cap / TVL of the LIVE-token protocols in the same
//              category (at least 3 live peers, else the global median),
//              clamped to [0.05, 1.00]. A category's own market tells us what
//              its tokens are worth relative to the value locked in it.
//   growth   = 1 + clamp(change_7d, -60, 150) / 100 * 0.60
//   maturity = 0.70 + min(age_days, 1095) / 1095 * 0.50   (age unknown: 365)
//   chain    = 1 + 0.02 * min(chains, 5)                 (multi-chain reach)
//   implied  = max(1, round(tvl_usd * peer * growth * maturity * chain))
//
// Rankable means: the record carries no token (no market cap, no CoinGecko id,
// no symbol), and it is not a wrapped, staked or bridged product of a token
// that already trades (excluded categories, exchange-prefixed names, wrapped /
// staked / staking in the name, versioned pool names). The watchlist is the
// floor: all 40 of its slugs are ranked, and the early radar adds every other
// rankable protocol below the floor. Live-token protocols are kept apart and
// shown with their market caps, never mixed into the ranking.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

